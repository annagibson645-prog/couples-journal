// Committed build step (no dependencies): node scripts/build.mjs
//  1. css/app.css  = the source stylesheets joined in order (sources stay the editable files)
//  2. index.html   = sigil tick/dot paths drawn in the markup (first paint needs no JS)
//  3. index.html   = <link rel="modulepreload"> for every file in the import graph (parallel download where supported)
//  4. js/boot.js   = a flat list of side-effect imports of every module, app.js then started.js last. Browsers without modulepreload
//     (before Safari 17) discover all modules one level deep instead of walking the nested import chain.
// tests/build.test.js fails if anything committed is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { importGraph } from './import-graph.mjs';
import { tickPath, dotPath } from '../js/lib/sigil.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const CSS_SOURCES = ['theme', 'layout', 'sigil', 'signin', 'journal', 'chart', 'export', 'notes'].map((n) => `css/${n}.css`);
const read = (p) => readFileSync(resolve(ROOT, p), 'utf8').replace(/\r\n/g, '\n');

export function buildCss() {
  return '/* GENERATED by scripts/build.mjs from the css/*.css sources. Edit those, then run: node scripts/build.mjs */\n' +
    CSS_SOURCES.map((p) => `/* --- ${p} --- */\n${read(p).trimEnd()}\n`).join('');
}

export function sigilD(kind, n) {
  return kind === 'dots' ? dotPath(n) : tickPath(n, kind === 'tick-long');
}

const SIGIL_RE = /<path data-sigil="([a-z-]+)" data-n="(\d+)"(?: d="[^"]*")?/g;
export function applySigils(html) {
  return html.replace(SIGIL_RE, (_m, kind, n) => `<path data-sigil="${kind}" data-n="${n}" d="${sigilD(kind, Number(n))}"`);
}

const PRE_RE = /(<!-- modulepreload:start -->\n)[\s\S]*?(  <!-- modulepreload:end -->)/;
export function preloadBlock() {
  return importGraph().files.map((f) => `  <link rel="modulepreload" href="${f}">\n`).join('');
}
export function applyPreloads(html) {
  return html.replace(PRE_RE, (_m, a, b) => a + preloadBlock() + b);
}

export function buildBoot() {
  const mods = importGraph('js/app.js').files.filter((f) => f !== 'js/app.js').map((f) => f.replace(/^js\//, './'));
  const head = [
    '// GENERATED by scripts/build.mjs. A flat list of every module, so browsers without modulepreload',
    '// (before Safari 17) fetch them all in parallel instead of walking the nested import chain.',
    '// The URLs match the real imports exactly, so each module is fetched and run once. app.js goes last, then started.js (it only sets the start flag).',
  ];
  return [...head, ...[...mods, './app.js', './started.js'].map((m) => `import '${m}';`)].join('\n') + '\n';
}

export function buildIndex(html) {
  return applyPreloads(applySigils(html));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(resolve(ROOT, 'css/app.css'), buildCss());
  writeFileSync(resolve(ROOT, 'js/boot.js'), buildBoot());
  const html = read('index.html');
  writeFileSync(resolve(ROOT, 'index.html'), buildIndex(html));
  console.log('built css/app.css and index.html');
}
